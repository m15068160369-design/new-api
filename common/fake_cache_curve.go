package common

// FakeCacheTokens [patch lou #6 v6] 返回免费渠道(ch11-20)假缓存注入的 cached_tokens，
// 双参数线性模型 cache = a·p − D（整数实现 (2497·p − 2507500)/2500，即
// a=0.9988=2497/2500、D=1003；返回 0 = 不注入，保留上游真实报告）。
// 参数按 ch21-40(ClinePass) 30天日志「连续使用」分支（真缓存占比≥80%，11,050 条）
// Theil-Sen 稳健回归拟合：a=0.9988、D=1003。数据结构是 D≈常数 + 每请求宽噪声
// （真实 U=p−cache 中位 1133、p10≈200/p90≈7000），斜率本≈0，双参不比单参拟合好
// （逐请求残差 855 vs 849）——双参的意义在隐蔽而非精度：v5 单参 p−1000 使注入后
// ch11 的 U 恒等于精确 1000（零散布），客户一减即破；v6 双参 U=(1−a)·p+D=
// 1003+3p/2500 随 p 变动（1003→~1300），「一减」不破。确定性公式在足够样本回归下
// 仍可还原，楼 20261016 拍板 B 案：确定性双参，不加每请求噪声（B+ 备选未采用）。
// 全区间一条公式无分段参数；p<10k 命中率自然走低（2k→49.7%、5k→79.8%、10k→89.9%），
// 复现真实小输入低命中形态，该区间比 v3 的 90% 少折扣、占 ch11 token <0.3%
// （随 B 案一并拍板：去 floor 放宽该区间不吃亏约束）。p≤~1003 值≤0 → 不注入，
// 客户端看真实 0（魔搭上游恒 0，即真实 miss 形态）。计费层(#6 v6)与帧层(#6b v6)
// 共用此单点定义，「0=不注入」语义两层一致，调参只改这里。纯整数算术（int64 中转
// 防溢出），无 IO 无随机。会话首条全 miss 的双峰行为不在拟合范围。
func FakeCacheTokens(promptTokens int) int {
	if promptTokens <= 0 {
		return 0
	}
	cache := (2497*int64(promptTokens) - 2507500) / 2500
	if cache <= 0 {
		return 0
	}
	return int(cache)
}
